
import base64
import hashlib
import hmac
import os
import secrets
import time

from dotenv import load_dotenv


load_dotenv()

SESSION_COOKIE_NAME = "chat_scholar_session"
SESSION_DURATION_SECONDS = 8 * 60 * 60  # 8 hours


def get_password_hash():
    password_hash = os.getenv(
        "CHAT_SCHOLAR_PASSWORD_HASH", ""
    )

    if not password_hash:
        raise RuntimeError(
            "CHAT_SCHOLAR_PASSWORD_HASH is not configured."
        )

    return password_hash


def get_session_secret():
    secret = os.getenv(
        "CHAT_SCHOLAR_SESSION_SECRET", ""
    )

    if len(secret) < 32:
        raise RuntimeError(
            "CHAT_SCHOLAR_SESSION_SECRET is missing "
            "or too short."
        )

    return secret.encode("utf-8")


def verify_password(password: str) -> bool:
    """
    Verify a password against the PBKDF2 hash
    generated by setup_v11_auth.py.
    """
    stored_hash = get_password_hash()

    try:
        algorithm, iterations, salt, expected = (
            stored_hash.split("$")
        )

        if algorithm != "pbkdf2_sha256":
            return False

        iterations = int(iterations)

        if not 100_000 <= iterations <= 2_000_000:
            return False

        salt_bytes = base64.b64decode(
            salt, validate=True
        )
        expected_bytes = base64.b64decode(
            expected, validate=True
        )

        calculated = hashlib.pbkdf2_hmac(
            "sha256",
            password.encode("utf-8"),
            salt_bytes,
            iterations
        )

        return hmac.compare_digest(
            calculated,
            expected_bytes
        )

    except (ValueError, TypeError):
        return False


def _sign(payload: str) -> str:
    """
    Generate an HMAC signature using the session secret.
    """
    secret = get_session_secret()

    signature = hmac.new(
        secret,
        payload.encode("utf-8"),
        hashlib.sha256
    ).digest()

    return base64.urlsafe_b64encode(
        signature
    ).decode("ascii").rstrip("=")


def create_session_token() -> str:
    """
    Create a signed token for an authenticated user.

    IMPORTANT:
    Only call this function AFTER successful
    password verification.
    """
    timestamp = int(time.time())
    nonce = secrets.token_urlsafe(16)

    payload = f"v1.{timestamp}.{nonce}"
    signature = _sign(payload)

    return f"{payload}.{signature}"


def verify_session_token(token: str) -> bool:
    """
    Check token integrity and expiration.

    Returns False if the token is malformed,
    altered, expired, or otherwise invalid.
    """
    if not isinstance(token, str):
        return False

    if not token or len(token) > 512:
        return False

    try:
        version, timestamp, nonce, signature = (
            token.split(".")
        )

        if version != "v1":
            return False

        if not timestamp.isascii() or not timestamp.isdigit():
            return False

        if not nonce or not signature:
            return False

        issued_at = int(timestamp)
        now = int(time.time())

        # Reject timestamps from the future.
        if issued_at > now:
            return False

        # Reject expired sessions.
        if now - issued_at >= SESSION_DURATION_SECONDS:
            return False

        payload = f"{version}.{timestamp}.{nonce}"
        expected_signature = _sign(payload)

        return hmac.compare_digest(
            signature,
            expected_signature
        )

    except (ValueError, TypeError):
        return False
